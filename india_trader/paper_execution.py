"""Paper execution boundary between lifecycle decisions and local settlement.

Only LocalPaperBroker implements this boundary in the current project. There is
deliberately no real brokerage adapter or order-routing API.
"""
from __future__ import annotations

from datetime import datetime
from typing import Any, Protocol


class PaperExecution(Protocol):
    def position(self, ticker: str) -> dict[str, Any] | None: ...
    def pending(self, ticker: str | None = None,
                side: str | None = None) -> list[dict[str, Any]]: ...
    def available_cash(self) -> Any: ...
    def submit(self, order: dict[str, Any], now: datetime) -> dict[str, Any]: ...
    def reject(self, proposal: dict[str, Any], now: datetime,
               reasons: list[str], signal_id: str) -> dict[str, Any] | None: ...
    def cancel(self, order: dict[str, Any], now: datetime, reason: str) -> None: ...
    def fill(self, order: dict[str, Any], now: datetime, quote: dict[str, Any],
             bar_volume: float, bar_start: str) -> dict[str, Any] | None: ...
